/**
 * میخکوب‌کردنِ زبان در محیطِ تست.
 *
 * زبانِ پیش‌فرضِ اپ از `navigator.language` خوانده می‌شود (تا نصب‌کننده‌ی فارسی
 * روی گوشیِ فارسی، اپ را فارسی ببیند). نتیجه‌اش در تست بد است: همان تست روی
 * ماشینِ انگلیسی‌زبان سبز و روی CIِ فارسی قرمز می‌شود — یا برعکس، چون بیشترِ
 * ادعاها روی متنِ فارسیِ رندرشده‌اند.
 *
 * پس اینجا محیط را «گوشیِ فارسی» تعریف می‌کنیم و تست‌ها ادعاهایشان را به یک
 * زبانِ ثابت گره می‌زنند. خودِ منطقِ تشخیص، در `i18n.test.ts` جدا تست می‌شود
 * (`systemLang`)، پس چیزی پوشیده نمی‌ماند.
 *
 * `navigator.language` در jsdom getterِ روی پروتوتایپ است؛ با تعریفِ مستقیم روی
 * خودِ آبجکت بازنویسی می‌شود و در محیطِ node هم (که Node ۲۱ به بعد `navigator`
 * دارد) همین راه کار می‌کند.
 */
const anyNav = globalThis.navigator as { language?: string } | undefined
if (anyNav) {
  try {
    Object.defineProperty(anyNav, 'language', { value: 'fa-IR', configurable: true })
  } catch {
    // اگر نشد، تست‌ها همان خطایِ قبلی را می‌دهند — بدتر از این نمی‌شود
  }
}
